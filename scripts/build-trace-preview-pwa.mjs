#!/usr/bin/env node
// Deterministic, local-only static cache. This script never edits production SW.
import {readFile,writeFile,lstat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const entry='trace-international-preview.html';
const html=await readFile(resolve(root,entry),'utf8');
const manifestPath='trace-international-preview.webmanifest';
const manifest=JSON.parse(await readFile(resolve(root,manifestPath),'utf8'));
if(manifest.start_url!=='./'+entry||manifest.scope!=='./'+entry||manifest.id!=='./'+entry)
 throw Error('Le manifeste doit rester exclusivement dans le laboratoire');
const assets=new Set([entry,manifestPath,'vendor/pdfjs/pdf.mjs','vendor/pdfjs/pdf.worker.mjs',
 'vendor/pdfjs/LICENSE','vendor/pdfjs/trace-vendor-manifest.json']);
for(const match of html.matchAll(/<(?:script|link)\b[^>]*\b(?:src|href)=["']([^"']+)["']/g))
 assets.add(match[1].split('?')[0]);
for(const icon of manifest.icons)assets.add(icon.src);
// Never accept a wildcard, a credential file, a remote origin, or a data PDF.
const names=[...assets].sort();
const hash=createHash('sha256');
hash.update(await readFile(fileURLToPath(import.meta.url)));
for(const name of names){
 if(!/^[a-zA-Z0-9_./-]+$/.test(name)||name.includes('..')||name.startsWith('/')||
    /^(?:index\.html|config\.js|cloud\.js|sw\.js|manifest\.webmanifest)$/.test(name)||
    !/\.(?:html|js|mjs|css|webmanifest|png|svg|json)$/.test(name)&&name!=='vendor/pdfjs/LICENSE')
  throw Error('Asset interdit dans le cache fictif : '+name);
 const file=resolve(root,name),stat=await lstat(file);
 if(!stat.isFile()||stat.isSymbolicLink())throw Error('Asset non régulier : '+name);
 hash.update(name+'\0');hash.update(await readFile(file));
}
const version=hash.digest('hex').slice(0,24);
const source=`/* GENERATED by scripts/build-trace-preview-pwa.mjs. Static fictional assets only. */
'use strict';
const BASE=new URL('./',self.location.href);
const ENTRY=new URL('${entry}',BASE);
const PREFIX='trace-lab-537:'+encodeURIComponent(BASE.pathname)+':';
const CACHE=PREFIX+'${version}';
const ASSETS=${JSON.stringify(names,null,1)};
const URLS=ASSETS.map(name=>new URL(name,BASE).href);
const ALLOWED=new Set(URLS);
if(self.registration.scope!==ENTRY.href)throw Error('Refusing a scope outside the fictional laboratory');
self.addEventListener('install',event=>event.waitUntil((async()=>{
 const cache=await caches.open(CACHE);
 // Protected HTTPS preview requires its same-origin Vercel session cookie
 // for static assets. Never attach cookies to any remote origin; URLS is
 // the generated same-origin allowlist, never finance data or runtime APIs.
 // A gateway can serve a login page with HTTP 200 and no redirect.
 // Validate all responses before any write: never cache HTML in place of
 // scripts, CSS, icons or PDF.js. Only static, exact-URL, same-origin 200s.
 const validType=(name,type)=>{
  if(name.endsWith('.js')||name.endsWith('.mjs'))
   return ['application/javascript','text/javascript','application/x-javascript'].includes(type);
  if(name.endsWith('.css'))return type==='text/css';
  if(name.endsWith('.html'))return type==='text/html';
  if(name.endsWith('.webmanifest'))
   return ['application/manifest+json','application/json'].includes(type);
  if(name.endsWith('.json'))return type==='application/json';
  if(name.endsWith('.svg'))return type==='image/svg+xml';
  if(name.endsWith('.png'))return type==='image/png';
  if(name.endsWith('/LICENSE'))
   return ['text/plain','application/octet-stream'].includes(type);
  return false;
 };
 const requests=URLS.map(url=>new Request(url,{
  cache:'reload',credentials:'same-origin',redirect:'error'
 }));
 try{
  // Browser-managed addAll avoids throttling concurrent worker fetches.
  // Verify each stored response before accepting the new worker generation.
  await cache.addAll(requests);
  const checked=await Promise.allSettled(requests.map(async(request,i)=>{
   const response=await cache.match(request);
   const type=(response?.headers.get('content-type')||'').split(';')[0].trim().toLowerCase();
   if(!response||response.status!==200||response.redirected||
      response.url!==request.url||response.type==='opaque'||!validType(ASSETS[i],type))
    throw Error('Refusing non-static or unauthenticated laboratory response: '+ASSETS[i]);
  }));
  if(checked.some(result=>result.status!=='fulfilled'))
   throw Error('Invalid response in fictional static cache');
 }catch(error){
  await caches.delete(CACHE);
  throw error;
 }
 if(!self.registration.active)await self.skipWaiting();
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
 for(const key of await caches.keys())if(key.startsWith(PREFIX)&&key!==CACHE)await caches.delete(key);
 await self.clients.claim();
})()));
self.addEventListener('message',event=>{
 if(event.data==='TRACE_LAB_ACTIVATE'&&event.source?.url&&
    new URL(event.source.url).origin===BASE.origin&&
    new URL(event.source.url).pathname===ENTRY.pathname)self.skipWaiting();
});
self.addEventListener('fetch',event=>{
 if(event.request.method!=='GET')return;
 const url=new URL(event.request.url);url.search='';url.hash='';
 if(url.origin!==BASE.origin||!ALLOWED.has(url.href))return;
 event.respondWith((async()=>{
  const cache=await caches.open(CACHE),saved=await cache.match(url.href);
  if(saved)return saved;
  // Never cache runtime responses, document data, statements, or requests.
  return fetch(event.request);
 })());
});
`;
const output=resolve(root,'trace-international-preview-sw.js');
if(process.argv.includes('--check')){
 if(await readFile(output,'utf8')!==source)throw Error('Cache laboratoire périmé : exécuter node scripts/build-trace-preview-pwa.mjs');
}else await writeFile(output,source);
console.log('Laboratory static cache '+version+': '+names.length+' assets, production untouched');
